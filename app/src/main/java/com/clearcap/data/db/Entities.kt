package com.clearcap.data.db

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

/** One recording. Status values are [com.clearcap.transcript.SessionStatus] names; versions are [com.clearcap.transcript.TextVersion] names. */
@Entity(tableName = "sessions")
data class SessionEntity(
    @PrimaryKey val id: String,
    val title: String,
    val startedAt: Long,
    val endedAt: Long?,
    val durationMs: Long,
    val status: String,
    val source: String,              // CaptureKind name, or LEGACY_* for imported transcripts
    val languageMode: String,        // LanguageMode code
    val detectedLanguage: String?,   // most common language reported by the model, when it reports one
    val liveMode: String,            // STREAMING | NEAR_LIVE | IMPORTED
    val liveModelId: String?,
    val refineModelId: String?,
    val activeVersion: String,
    val editedText: String?,
    val behindMs: Long,
    val droppedMs: Long,
    val audioFile: String?,          // file name inside the private audio folder while audio is kept
    val notes: String?,              // text imported from earlier versions; never generated by a cloud service
    val statusNote: String?,
    val imported: Boolean,
)

@Entity(
    tableName = "segments",
    primaryKeys = ["sessionId", "idx"],
    foreignKeys = [ForeignKey(entity = SessionEntity::class, parentColumns = ["id"], childColumns = ["sessionId"], onDelete = ForeignKey.CASCADE)],
    indices = [Index(value = ["sessionId"])],
)
data class SegmentEntity(
    val sessionId: String,
    val idx: Int,
    val startMs: Long,
    val endMs: Long,
    val liveText: String,
    val refinedText: String?,
    val rawText: String?,
    val language: String?,
)

@Entity(tableName = "vocabulary", indices = [Index(value = ["term"], unique = true)])
data class VocabularyEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val term: String,
    val spokenAs: String,            // aliases, one per line
    val createdAt: Long,
)
